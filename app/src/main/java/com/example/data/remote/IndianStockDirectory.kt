    fun resolveOrSynthesizeStock(symbolOrQuery: String, preferredExchange: Exchange = Exchange.NSE): StockQuote {
        val cleanSymbol = symbolOrQuery.trim().uppercase()
        
        // 0. Index alias normalization
        val normalizedSymbol = when (cleanSymbol.replace(" ", "").replace("_", "").replace("-", "")) {
            "NIFTY", "NIFTY50", "NSEI", "^NSEI" -> "NIFTY 50"
            "BANKNIFTY", "NIFTYBANK", "NSEBANK", "^NSEBANK" -> "BANK NIFTY"
            "SENSEX", "BSESENSEX", "BSESN", "^BSESN" -> "SENSEX"
            "FINNIFTY", "NIFTYFIN", "NIFTYFINANCIAL" -> "FINNIFTY"
            "MIDCPNIFTY", "NIFTYMIDCAP", "NIFTYMIDSELECT" -> "MIDCPNIFTY"
            else -> cleanSymbol
        }

        // 1. Exact or partial symbol match
        val existing = allMasterStocks.find { 
            it.symbol.equals(normalizedSymbol, ignoreCase = true) || 
            it.symbol.equals(cleanSymbol, ignoreCase = true) ||
            it.companyName.contains(cleanSymbol, ignoreCase = true) 
        }
        if (existing != null) return existing

        // 2. Synthesize on-the-fly for any valid stock symbol
        val hash = kotlin.math.abs(cleanSymbol.hashCode())
        val pseudoPrice = ((hash % 4500) + 75.0).let { Math.round(it * 100.0) / 100.0 }
        val pseudoChangePct = (((hash % 900) - 420) / 100.0)
        val pseudoChange = Math.round((pseudoPrice * (pseudoChangePct / 100.0)) * 100.0) / 100.0
        val prevClose = Math.round((pseudoPrice - pseudoChange) * 100.0) / 100.0
        val high = Math.round((pseudoPrice * 1.025) * 100.0) / 100.0
        val low = Math.round((pseudoPrice * 0.975) * 100.0) / 100.0
        val high52 = Math.round((pseudoPrice * 1.35) * 100.0) / 100.0
        val low52 = Math.round((pseudoPrice * 0.65) * 100.0) / 100.0
        val token = "${(hash % 90000) + 10000}"

        val detectedSector = when {
            cleanSymbol.contains("BANK") || cleanSymbol.contains("FIN") -> "Banking & Financial Services"
            cleanSymbol.contains("TECH") || cleanSymbol.contains("SOFT") || cleanSymbol.contains("INFO") -> "Information Technology"
            cleanSymbol.contains("PHARMA") || cleanSymbol.contains("LAB") || cleanSymbol.contains("HEALTH") -> "Pharmaceuticals & Healthcare"
            cleanSymbol.contains("AUTO") || cleanSymbol.contains("MOT") || cleanSymbol.contains("TYRE") -> "Automobile & Mobility"
            cleanSymbol.contains("POWER") || cleanSymbol.contains("ENER") || cleanSymbol.contains("SOLAR") -> "Power & Green Energy"
            cleanSymbol.contains("STEEL") || cleanSymbol.contains("MET") || cleanSymbol.contains("MINE") -> "Metals & Mining"
            cleanSymbol.contains("RAIL") -> "Railways Infrastructure"
            cleanSymbol.contains("DEF") || cleanSymbol.contains("AERO") -> "Defense & Aerospace"
            cleanSymbol.contains("PROP") || cleanSymbol.contains("REAL") || cleanSymbol.contains("EST") -> "Real Estate"
            else -> "Equities & General Industry"
        }

        return StockQuote(
            symbol = cleanSymbol,
            companyName = "$cleanSymbol India Ltd",
            exchange = preferredExchange,
            token = token,
            currentPrice = pseudoPrice,
            change = pseudoChange,
            percentChange = pseudoChangePct,
            open = prevClose,
            high = high,
            low = low,
            previousClose = prevClose,
            volume = ((hash % 15000000L) + 500000L),
            high52Week = high52,
            low52Week = low52,
            sector = detectedSector,
            marketCap = "₹${(hash % 90) + 5},${(hash % 900)} Cr"
        )
    }
